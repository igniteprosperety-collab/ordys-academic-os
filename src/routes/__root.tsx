function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="pt-BR">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    void initializeNativeAuth().catch((error) => {
      console.error("Native auth initialization failed:", error);
    });

    const onNativeAuth = (event: Event) => {
      const detail = (event as CustomEvent<NativeAuthEventDetail>).detail;
      if (detail?.status === "success" && detail.purpose === "recovery") {
        void router.navigate({ to: "/redefinir-senha", replace: true });
      }
    };

    window.addEventListener(NATIVE_AUTH_EVENT, onNativeAuth);
    return () => window.removeEventListener(NATIVE_AUTH_EVENT, onNativeAuth);
  }, [router]);

  useEffect(() => {
    const { data } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
    });
    return () => data.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <Toaster position="bottom-right" theme="dark" />
    </QueryClientProvider>
  );
}
